--------------------------------------------------------------------------------
-- Galaxian sound, "classic" version: FBNeo's Galaxian sound
-- (src/burn/drv/galaxian/gal_sound.cpp), which is a port of the pre-discrete
-- MAME sound (MAME 0.36b11 - 0.133u1, src/mame/audio/galaxian.c) plus a
-- filtered explosion added by FBNeo in 2025.
--
-- One output sample every 250 clocks (48 kHz, FBNeo's sample rate here). A
-- sample is computed by a short sequence of states (st) that follows FBNeo's
-- render order and integer/float truncations:
--   * tone: 16 sub steps of the reloading pitch counter, 4 wave tables (VOL)
--   * explosion: LFSR noise at 8 kHz, volume envelope counted in frames,
--     low shelf 150 Hz + low pass 550 Hz biquads (fixed point, one shared
--     multiplier; signals Q20, coefficients Q25)
--   * fire: precomputed 2 s wave at 22050 Hz (ROM in the package)
--   * swarm: three square waves, pitch swept down once per frame
-- Each channel is scaled and added with FBNeo's 16 bit clipping.
-- Register writes and the frame tick are taken at the start of a sample.
-- Constants come from rtl/galaxian_snd_fbn_pkg.vhd, generated by
-- sim/galaxian_sound/fbn_ref.cpp.
--------------------------------------------------------------------------------
library ieee;
	use ieee.std_logic_1164.all;
	use ieee.numeric_std.all;

use work.galaxian_snd_fbn_pkg.all;

entity GALAXIAN_SND_FBN is
port (
	I_CLK_12M  : in  std_logic;
	I_RESET    : in  std_logic;
	I_BD       : in  std_logic_vector(7 downto 0);  -- CPU data bus
	I_PITCH_WE : in  std_logic;                     -- pitch latch write
	I_FS       : in  std_logic_vector(2 downto 0);  -- 9L Q0-Q2
	I_HIT_WR   : in  std_logic;                     -- write of 1 to 9L Q3
	I_FIRE     : in  std_logic;                     -- 9L Q5
	I_VOL1     : in  std_logic;                     -- 9L Q6
	I_VOL2     : in  std_logic;                     -- 9L Q7
	I_DAC      : in  std_logic_vector(3 downto 0);  -- 9M Q4-Q7 (bit 0 = 1M)
	I_VSYNC    : in  std_logic;                     -- frame tick on rising edge
	O_AUDIO    : out std_logic_vector(15 downto 0); -- signed
	O_SAMPLE   : out std_logic                      -- new sample strobe (simulation watchdog)
);
end;

architecture RTL of GALAXIAN_SND_FBN is

	subtype s40 is signed(39 downto 0);

	function clip16(x : integer) return integer is
	begin
		if x > 32767 then return 32767; elsif x < -32768 then return -32768; else return x; end if;
	end;

	-- one shift of FBNeo's noise generator (Generator <<= 1; bit 0 = ~bit17 ^ bit5)
	function lfsr_shift(g : unsigned(17 downto 0)) return unsigned is
		variable n : unsigned(17 downto 0);
	begin
		n := g(16 downto 0) & '0';
		n(0) := (not n(17)) xor n(5);
		return n;
	end;

	constant LFO_TOP : unsigned(37 downto 0) := shift_left(to_unsigned(32, 38), 32);

	signal div      : integer range 0 to 249 := 0;
	signal st       : integer range 0 to 31 := 31;

	-- events
	signal hit_wr_l, vs_l : std_logic := '0';
	signal hit_pend, frame_pend, pitch_pend : std_logic := '0';
	signal pitch_new : unsigned(7 downto 0) := x"ff";

	-- inputs taken at the start of a sample
	signal fs     : std_logic_vector(2 downto 0) := "000";
	signal vol    : integer range 0 to 3 := 0;
	signal fire_l : std_logic := '0';

	-- tone
	signal pitch   : unsigned(7 downto 0) := x"ff";
	signal t_cnt   : unsigned(3 downto 0) := (others => '0');
	signal t_cd    : integer range 0 to 255 := 0;
	signal t_mix   : integer range -262144 to 262144 := 0;

	-- explosion
	signal n_vol   : integer range 0 to 100 := 0;
	signal n_hold  : integer range 0 to 20 := 0;
	signal f3      : integer range 0 to 2 := 0;
	signal n_idx   : integer range 0 to 32767 := 0;
	signal n_frac  : integer range 0 to 5 := 0;
	signal n_gen   : unsigned(17 downto 0) := to_unsigned(NOISE_G0, 18);
	signal n_shift : integer range 0 to 96 := 0;
	signal x, y, s, tA, tB : s40 := (others => '0');
	signal ls_z1, ls_z2, lp_z1, lp_z2 : s40 := (others => '0');
	signal n_out   : integer range -32768 to 32767 := 0;
	signal mp      : signed(62 downto 0) := (others => '0');

	-- fire
	signal sh_en   : std_logic := '0';
	signal sh_idx  : integer range 0 to SHOOT_LEN := 0;
	signal sh_frac : integer range 0 to 319 := 0;
	signal sh_q    : unsigned(9 downto 0) := (others => '0');
	signal sh_rom  : shoot_rom_t := SHOOT_ROM;
	attribute romstyle : string;
	attribute romstyle of sh_rom : signal is "M10K";

	-- swarm
	type u38_array is array(0 to 2) of unsigned(37 downto 0);
	signal lfo_f    : signed(41 downto 0) := shift_left(to_signed(LFO_MAX, 42), 32);
	signal lfo_pos  : u38_array := (others => (others => '0'));
	signal lfo_step : u38_array := (others => (others => '0'));

	signal audio : integer range -32768 to 32767 := 0;

begin

	O_AUDIO <= std_logic_vector(to_signed(audio, 16));
	O_SAMPLE <= '1' when st = 18 else '0';

	-- fire wave ROM
	process(I_CLK_12M)
	begin
		if rising_edge(I_CLK_12M) then
			sh_q <= sh_rom(sh_idx);
		end if;
	end process;

	process(I_CLK_12M)
		variable ma : signed(35 downto 0);
		variable mb : signed(26 downto 0);
		variable use_m : boolean;
		variable cd : integer range 0 to 255;
		variable cnt : unsigned(3 downto 0);
		variable mix : integer range -262144 to 262144;
		variable ts, b, v, nf, ni : integer;
		variable p : unsigned(37 downto 0);
		variable g : unsigned(17 downto 0);
	begin
		if rising_edge(I_CLK_12M) then
			if I_RESET = '1' then
				div <= 0; st <= 31;
				hit_wr_l <= '0'; vs_l <= '0';
				hit_pend <= '0'; frame_pend <= '0'; pitch_pend <= '0'; pitch_new <= x"ff";
				fs <= "000"; vol <= 0; fire_l <= '0';
				pitch <= x"ff"; t_cnt <= (others => '0'); t_cd <= 0; t_mix <= 0;
				n_vol <= 0; n_hold <= 0; f3 <= 0; n_idx <= 0; n_frac <= 0;
				n_gen <= to_unsigned(NOISE_G0, 18); n_shift <= 0;
				ls_z1 <= (others => '0'); ls_z2 <= (others => '0');
				lp_z1 <= (others => '0'); lp_z2 <= (others => '0');
				n_out <= 0;
				sh_en <= '0'; sh_idx <= 0; sh_frac <= 0;
				lfo_f <= shift_left(to_signed(LFO_MAX, 42), 32);
				lfo_pos <= (others => (others => '0'));
				audio <= 0;
			else
				-- events, kept until the next sample start
				hit_wr_l <= I_HIT_WR;
				vs_l <= I_VSYNC;
				if I_HIT_WR = '1' and hit_wr_l = '0' then hit_pend <= '1'; end if;
				if I_VSYNC = '1' and vs_l = '0' then frame_pend <= '1'; end if;
				if I_PITCH_WE = '1' then pitch_pend <= '1'; pitch_new <= unsigned(I_BD); end if;

				-- noise generator catches up with the sample index, 8 shifts a clock
				if n_shift /= 0 then
					g := n_gen;
					for i in 1 to 8 loop g := lfsr_shift(g); end loop;
					n_gen <= g;
					n_shift <= n_shift - 1;
				end if;

				if div = 249 then div <= 0; else div <= div + 1; end if;
				if div = 0 then st <= 0; elsif st /= 31 then st <= st + 1; end if;

				use_m := false;
				ma := (others => '0'); mb := (others => '0');

				case st is
				when 0 =>
					-- GalaxianSoundUpdateTimers (once per frame)
					if frame_pend = '1' and not (I_VSYNC = '1' and vs_l = '0') then
						frame_pend <= '0';
					end if;
					v := n_vol; b := n_hold;
					if frame_pend = '1' then
						if b /= 0 then b := b - 1; end if;
						if f3 = 0 and b = 0 and v > 0 then
							v := v - (v / 10 + 1);
							if v < 0 then v := 0; end if;
						end if;
						if f3 = 2 then f3 <= 0; else f3 <= f3 + 1; end if;
						if lfo_f > shift_left(to_signed(LFO_MIN, 42), 32) then
							lfo_f <= lfo_f - signed(resize(LFO_FRAME_VAR(to_integer(unsigned(I_DAC))), 42));
						else
							lfo_f <= shift_left(to_signed(LFO_MAX, 42), 32);
						end if;
					end if;
					-- register writes
					if hit_pend = '1' then
						if not (I_HIT_WR = '1' and hit_wr_l = '0') then hit_pend <= '0'; end if;
						if b = 0 then
							n_idx <= 0; n_frac <= 0;
							n_gen <= to_unsigned(NOISE_G0, 18); n_shift <= 0;
						end if;
						b := 20; v := 100;
					end if;
					n_vol <= v; n_hold <= b;
					fire_l <= I_FIRE;
					if I_FIRE = '1' and fire_l = '0' then
						sh_en <= '1'; sh_idx <= 0; sh_frac <= 0;
					end if;
					if pitch_pend = '1' then
						if I_PITCH_WE = '0' then pitch_pend <= '0'; end if;
						pitch <= pitch_new;
					end if;
					fs <= I_FS;
					vol <= to_integer(unsigned'(I_VOL2 & I_VOL1));
					t_mix <= 0;

				when 1 =>
					-- explosion input: (INT16)(wave * vol/100) / 10
					if n_gen(17) = '1' then
						x <= shift_left(to_signed( NOISE_AMP(n_vol), 40), 20);
					else
						x <= shift_left(to_signed(-NOISE_AMP(n_vol), 40), 20);
					end if;

				-- swarm wave steps: frequency * K, Q27 * Q35 >> 30 = Q32
				when 2 | 3 | 4 =>
					use_m := true;
					ma := resize(shift_right(lfo_f, 5), 36);
					mb := to_signed(LFO_STEP_K(st - 2), 27);
				when 5 =>
					use_m := true; ma := resize(x, 36); mb := to_signed(LS_A0, 27);

				-- low shelf, transposed direct form II
				when 6 =>
					y <= resize(shift_right(mp, 25), 40) + ls_z1;
					use_m := true; ma := resize(x, 36); mb := to_signed(LS_A1, 27);
				when 7 =>
					tA <= resize(shift_right(mp, 25), 40) + ls_z2;
					use_m := true; ma := resize(y, 36); mb := to_signed(LS_B1, 27);
				when 8 =>
					tA <= tA - resize(shift_right(mp, 25), 40);
					use_m := true; ma := resize(x, 36); mb := to_signed(LS_A2, 27);
				when 9 =>
					tB <= resize(shift_right(mp, 25), 40);
					use_m := true; ma := resize(y, 36); mb := to_signed(LS_B2, 27);
				when 10 =>
					ls_z2 <= tB - resize(shift_right(mp, 25), 40);
					ls_z1 <= tA;
					s <= y + x;

				-- low pass
				when 11 =>
					use_m := true; ma := resize(s, 36); mb := to_signed(LP_A0, 27);
				when 12 =>
					y <= resize(shift_right(mp, 25), 40) + lp_z1;
					use_m := true; ma := resize(s, 36); mb := to_signed(LP_A1, 27);
				when 13 =>
					tA <= resize(shift_right(mp, 25), 40) + lp_z2;
					use_m := true; ma := resize(y, 36); mb := to_signed(LP_B1, 27);
				when 14 =>
					tA <= tA - resize(shift_right(mp, 25), 40);
					use_m := true; ma := resize(s, 36); mb := to_signed(LP_A2, 27);
				when 15 =>
					tB <= resize(shift_right(mp, 25), 40);
					use_m := true; ma := resize(y, 36); mb := to_signed(LP_B2, 27);
				when 16 =>
					lp_z2 <= tB - resize(shift_right(mp, 25), 40);
					lp_z1 <= tA;
					-- (INT16) of the filter output truncates toward zero
					if y < 0 then
						n_out <= -to_integer(shift_right(-y, 20));
					else
						n_out <= to_integer(shift_right(y, 20));
					end if;

				-- mix in FBNeo's order, each channel * 4 with clipping
				when 17 =>
					if pitch /= x"ff" then
						-- (INT16)(mix / 16) >> 4: "/" truncates toward zero, ">>" floors
						ts := to_integer(shift_right(to_signed(t_mix / 16, 20), 4));
						b := clip16(ts * 4);
					else
						b := 0;
					end if;
					b := clip16(b + clip16(n_out * 4));
					if sh_en = '1' then
						b := clip16(b + to_integer(sh_q) * 4);
						-- position += 22050 / 48000 = 147 / 320, stop past the end
						nf := sh_frac + 147; ni := sh_idx;
						if nf >= 320 then nf := nf - 320; ni := ni + 1; end if;
						if ni > SHOOT_LEN or (ni = SHOOT_LEN and nf > 0) then
							sh_en <= '0'; sh_idx <= 0; sh_frac <= 0;
						else
							sh_idx <= ni; sh_frac <= nf;
						end if;
					end if;
					for i in 0 to 2 loop
						if fs(i) = '1' then
							if lfo_pos(i)(36) = '0' then b := clip16(b + 244); else b := clip16(b - 248); end if;
						end if;
						p := lfo_pos(i) + lfo_step(i);
						if p > LFO_TOP then lfo_pos(i) <= (others => '0'); else lfo_pos(i) <= p; end if;
					end loop;
					audio <= b;
					-- explosion wave position, 8000 / 48000 per sample
					nf := n_frac + 1; ni := n_idx;
					if nf = 6 then nf := 0; ni := ni + 1; end if;
					if ni > 32000 or (ni = 32000 and nf > 0) then
						n_idx <= 0; n_frac <= 0; n_gen <= to_unsigned(NOISE_G0, 18); n_shift <= 0;
					else
						n_idx <= ni; n_frac <= nf;
						if nf = 0 then n_shift <= 96; end if;
					end if;

				when others => null;
				end case;

				-- swarm steps come out of the multiplier one state later
				if st >= 3 and st <= 5 then
					lfo_step(st - 3) <= unsigned(resize(shift_right(mp, 30), 38));
				end if;

				-- tone sub steps in states 1..16 (GalRenderToneWave)
				if st >= 1 and st <= 16 and pitch /= x"ff" then
					cd := t_cd; cnt := t_cnt; mix := t_mix;
					if cd >= 128 then
						cnt := cnt + 1;
						cd := to_integer(pitch(7 downto 1));
					end if;
					cd := cd + 1;
					mix := mix + TONE_WAVE(vol * 16 + to_integer(cnt));
					t_cd <= cd; t_cnt <= cnt; t_mix <= mix;
				end if;

				if use_m then mp <= ma * mb; end if;
			end if;
		end if;
	end process;

end RTL;
