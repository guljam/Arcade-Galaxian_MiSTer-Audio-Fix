--------------------------------------------------------------------------------
-- Galaxian / Moon Cresta sound board
--
-- Fixed point model of the analog sound circuit, following MAME's discrete
-- netlist (src/mame/galaxian/galaxian_a.cpp: galaxian_discrete and
-- mooncrst_discrete). Node names in the comments refer to that netlist.
--
--  * background "swarm": 4 bit R-ladder DAC -> 555 constant current sawtooth
--    LFO (NODE_105) -> control voltage of three 555 astables (8R/8S/8T)
--    -> resistor mixer with C20 low pass (NODE_120)
--  * pitch: 8 bit reloading counter + 74393 (NODE_132/133), bits QA/QC/QD
--  * hit: LFSR noise sampled at 2V, RC envelope (NODE_155), op-amp
--    band pass with rail clipping (NODE_157)
--  * fire: noise + RC sweep as control voltage of a 555 (NODE_181),
--    RC envelope (NODE_182)
--  * mixer: VOL1/VOL2 switch resistors in and out, C46 output coupling
--
-- The analog part is stepped at 750 kHz (12 MHz / 16). Voltages are signed
-- 40 bit numbers with 32 fraction bits (1.0 V = 2**32). Constants come from
-- rtl/galaxian_snd_pkg.vhd, generated by sim/galaxian_sound/gen_consts.py.
--
-- O_AUDIO is signed, scaled like MAME's output (1.0 V = full scale).
--------------------------------------------------------------------------------
library ieee;
	use ieee.std_logic_1164.all;
	use ieee.numeric_std.all;

use work.galaxian_snd_pkg.all;

entity GALAXIAN_SND is
port (
	I_CLK_12M  : in  std_logic;
	I_RESET    : in  std_logic;
	I_MOONCR   : in  std_logic;                     -- 1 = Moon Cresta mixer
	I_BD       : in  std_logic_vector(7 downto 0);  -- CPU data bus
	I_PITCH_WE : in  std_logic;                     -- 9J pitch latch write
	I_FS       : in  std_logic_vector(2 downto 0);  -- 9L Q0-Q2
	I_HIT      : in  std_logic;                     -- 9L Q3
	I_FIRE     : in  std_logic;                     -- 9L Q5
	I_VOL1     : in  std_logic;                     -- 9L Q6
	I_VOL2     : in  std_logic;                     -- 9L Q7
	I_DAC      : in  std_logic_vector(3 downto 0);  -- 9M Q4-Q7 (bit 0 = 1M)
	O_AUDIO    : out std_logic_vector(15 downto 0);
	-- simulation taps (volts, 40 bit): fire_out & hit_out & bg & cv & lfo_cap, step strobe
	O_DBG      : out std_logic_vector(199 downto 0);
	O_DBG_STEP : out std_logic
);
end;

architecture RTL of GALAXIAN_SND is

	subtype volt_t is signed(39 downto 0);
	constant ZERO : volt_t := (others => '0');
	constant SAT_HI : volt_t := shift_left(to_signed( 32767, 40), 17);
	constant SAT_LO : volt_t := shift_left(to_signed(-32768, 40), 17);

	-- x * k_int / 2**s for |x| < 8 V, one 27x27 multiplier, rounded
	function mulc(x : volt_t; k : integer; s : integer) return volt_t is
		variable p : signed(53 downto 0);
	begin
		p := x(35 downto 9) * to_signed(k, 27);
		p := p + shift_left(to_signed(1, 54), s - 10);
		return resize(shift_right(p, s - 9), 40);
	end;

	-- DSD_555_ASTBL with control voltage (R1/R2/C fixed, v_charge = 5 V)
	procedure astable(en : std_logic; cv : volt_t; kc, kd, s : integer;
	                  v : inout volt_t; ff : inout std_logic) is
		variable th, tr, a, vn : volt_t;
		variable k : integer;
	begin
		if en = '0' then
			v := ZERO; ff := '1';
		elsif cv >= V_025 then   -- MAME ignores control voltages below 0.25 V
			th := cv;
			tr := shift_right(cv, 1);
			if v >= th then ff := '0'; elsif v <= tr then ff := '1'; end if;
			if ff = '1' then a := V_5 - v; k := kc; else a := ZERO - v; k := kd; end if;
			vn := v + mulc(a, k, s);
			if ff = '1' then
				if vn >= th then vn := th; ff := '0'; end if;
			else
				if vn <= tr then vn := tr; ff := '1'; end if;
			end if;
			v := vn;
		end if;
	end;

	-- DST_RCDISC5: diode charges the cap instantly, discharge through R only while enabled
	procedure rcdisc5(en : std_logic; u : volt_t; k, s : integer;
	                  cap : inout volt_t; o : out volt_t) is
	begin
		if en = '1' then
			if u < cap then cap := cap + mulc(u - cap, k, s); else cap := u; end if;
			o := cap;
		else
			if u > cap then cap := u; end if;
			o := ZERO;
		end if;
	end;

	signal step_cnt  : unsigned(3 downto 0) := (others => '0');

	-- pitch (9J latch, 2x LS161 reload counter, 74393)
	signal pitch     : unsigned(7 downto 0) := (others => '1');
	signal clk_acc   : unsigned(6 downto 0) := (others => '0');
	signal note_c1   : unsigned(7 downto 0) := (others => '1');
	signal note_c2   : unsigned(3 downto 0) := (others => '0');
	signal acc_a, acc_c, acc_d : unsigned(4 downto 0) := (others => '0');
	signal cnt_a, cnt_c, cnt_d : unsigned(4 downto 0) := (others => '0');

	-- noise: 17 bit LFSR at 122.88 kHz, sampled on 2V (7920 Hz)
	signal rng_acc   : unsigned(13 downto 0) := (others => '0');
	signal v2_acc    : unsigned(15 downto 0) := (others => '0');
	signal lfsr      : std_logic_vector(17 downto 0) := (17 => '1', others => '0');
	signal noise     : std_logic := '0';

	-- analog state
	signal lfo_cap   : volt_t := ZERO;
	signal cv        : volt_t := ZERO;
	signal vco_cap1, vco_cap2, vco_cap3 : volt_t := ZERO;
	signal vco_ff    : std_logic_vector(2 downto 0) := (others => '1');
	signal bg        : volt_t := ZERO;
	signal hit_cap   : volt_t := ZERO;
	signal bp_x1, bp_x2, bp_y1, bp_y2 : volt_t := ZERO;
	signal hit_out   : volt_t := BP_VREF;
	signal f173      : volt_t := ZERO;
	signal fvco_cap  : volt_t := ZERO;
	signal fvco_ff   : std_logic := '1';
	signal f182_cap  : volt_t := ZERO;
	signal fire_out  : volt_t := ZERO;
	signal c26_cap   : volt_t := ZERO;
	signal amp_cap   : volt_t := AMP_DC_GAL;
	signal audio     : signed(15 downto 0) := (others => '0');

begin

	O_AUDIO <= std_logic_vector(audio);
	O_DBG   <= std_logic_vector(fire_out & hit_out & bg & cv & lfo_cap);
	O_DBG_STEP <= '1' when step_cnt = 1 else '0';

	-- digital part, every 12 MHz clock
	process(I_CLK_12M)
		variable fb : std_logic;
		variable l  : std_logic_vector(17 downto 0);
	begin
		if rising_edge(I_CLK_12M) then
			if I_RESET = '1' then
				step_cnt <= (others => '0');
				pitch    <= (others => '1');
				clk_acc  <= (others => '0');
				note_c1  <= (others => '1');
				note_c2  <= (others => '0');
				acc_a <= (others => '0'); acc_c <= (others => '0'); acc_d <= (others => '0');
				rng_acc  <= (others => '0');
				v2_acc   <= (others => '0');
				lfsr     <= (17 => '1', others => '0');
				noise    <= '0';
			else
				step_cnt <= step_cnt + 1;

				if I_PITCH_WE = '1' then
					pitch <= unsigned(I_BD);
				end if;

				-- NODE_132: 1.536 MHz = 12 MHz * 16 / 125
				if clk_acc >= 125 - 16 then
					clk_acc <= clk_acc - (125 - 16);
					if pitch /= 255 then
						if note_c1 = 255 then
							note_c1 <= pitch;
							note_c2 <= note_c2 + 1;
						else
							note_c1 <= note_c1 + 1;
						end if;
					end if;
				else
					clk_acc <= clk_acc + 16;
				end if;

				-- time each 74393 output is high during a step (0..16 clocks)
				if step_cnt = 15 then
					cnt_a <= acc_a + ("0000" & note_c2(0));
					cnt_c <= acc_c + ("0000" & note_c2(2));
					cnt_d <= acc_d + ("0000" & note_c2(3));
					acc_a <= (others => '0'); acc_c <= (others => '0'); acc_d <= (others => '0');
				else
					acc_a <= acc_a + ("0000" & note_c2(0));
					acc_c <= acc_c + ("0000" & note_c2(2));
					acc_d <= acc_d + ("0000" & note_c2(3));
				end if;

				-- NODE_150: LFSR clocked at 122.88 kHz = 12 MHz * 128 / 12500
				if rng_acc >= 12500 - 128 then
					rng_acc <= rng_acc - (12500 - 128);
					l := lfsr;
					fb := l(17);
					l(16 downto 0) := l(15 downto 0) & fb;
					l(17) := not (l(4) xor l(16));
					lfsr <= l;
				else
					rng_acc <= rng_acc + 128;
				end if;

				-- NODE_151/152: sampled on the rising edge of 2V, 7920 Hz = 12 MHz * 33 / 50000
				if v2_acc >= 50000 - 33 then
					v2_acc <= v2_acc - (50000 - 33);
					noise  <= lfsr(17);
				else
					v2_acc <= v2_acc + 33;
				end if;
			end if;
		end if;
	end process;

	-- analog part, one step every 16 clocks
	process(I_CLK_12M)
		variable idx   : integer range 0 to 7;
		variable lfo, cvv, v1, v2, v3, fv : volt_t;
		variable ff    : std_logic_vector(2 downto 0);
		variable fff   : std_logic;
		variable tgt   : volt_t;
		variable u, hc, n155, fc, n182 : volt_t;
		variable y, dx : volt_t;
		variable c26, vf, mix, amp, o : volt_t;
	begin
		if rising_edge(I_CLK_12M) then
			if I_RESET = '1' then
				lfo_cap  <= ZERO;
				cv       <= ZERO;
				vco_cap1 <= ZERO; vco_cap2 <= ZERO; vco_cap3 <= ZERO;
				vco_ff   <= (others => '1');
				bg       <= ZERO;
				hit_cap  <= ZERO;
				bp_x1 <= ZERO; bp_x2 <= ZERO; bp_y1 <= ZERO; bp_y2 <= ZERO;
				hit_out  <= BP_VREF;
				f173     <= ZERO;
				fvco_cap <= ZERO;
				fvco_ff  <= '1';
				f182_cap <= ZERO;
				fire_out <= ZERO;
				c26_cap  <= ZERO;
				if I_MOONCR = '1' then amp_cap <= AMP_DC_MC; else amp_cap <= AMP_DC_GAL; end if;
				audio    <= (others => '0');
			elsif step_cnt = 0 then
				------------------------------------------------ background
				-- NODE_105: 555 constant current sawtooth, immediate discharge to 1/3 Vcc
				lfo := lfo_cap + to_signed(LFO_SLOPE(to_integer(unsigned(I_DAC))), 40);
				if lfo >= LFO_TH then lfo := lfo - LFO_SPAN; end if;
				lfo_cap <= lfo;

				-- NODE_110/111: op-amp mult/add, clamped to the rails
				cvv := mulc(lfo_cap, CV_GAIN_K, CV_GAIN_S) + CV_OFS;
				if cvv < ZERO then cvv := ZERO; elsif cvv > V_5 then cvv := V_5; end if;
				cv <= cvv;

				-- NODE_115..117: 555 VCOs, held in reset by FS1..FS3
				v1 := vco_cap1; v2 := vco_cap2; v3 := vco_cap3; ff := vco_ff;
				astable(I_FS(0), cv, VCO1_KC, VCO1_KD, VCO1_S, v1, ff(0));
				astable(I_FS(1), cv, VCO2_KC, VCO2_KD, VCO2_S, v2, ff(1));
				astable(I_FS(2), cv, VCO3_KC, VCO3_KD, VCO3_S, v3, ff(2));
				vco_cap1 <= v1; vco_cap2 <= v2; vco_cap3 <= v3; vco_ff <= ff;

				-- NODE_120: 3 x 10k mixer into C20
				tgt := ZERO;
				if I_FS(0) = '1' and vco_ff(0) = '1' then tgt := tgt + VCO_HIGH_X1_5; end if;
				if I_FS(1) = '1' and vco_ff(1) = '1' then tgt := tgt + VCO_HIGH_X1_5; end if;
				if I_FS(2) = '1' and vco_ff(2) = '1' then tgt := tgt + VCO_HIGH_X1_5; end if;
				bg <= bg + mulc(tgt - bg, BG_K_K, BG_K_S);

				------------------------------------------------ hit
				-- NODE_155
				if I_HIT = '1' then u := HIT_U; else u := ZERO; end if;
				hc := hit_cap;
				rcdisc5(noise, u, HIT_K_K, HIT_K_S, hc, n155);
				hit_cap <= hc;

				-- NODE_157: band pass, y = b0*(x - x2) - a1*y1 - a2*y2, clipped to the op-amp rails
				dx := n155 - bp_x2;
				y  := shift_left(bp_y1, 1) - bp_y2 + mulc(bp_y1, BP_C1_K, BP_C1_S)
				      + mulc(bp_y2, BP_C2_K, BP_C2_S) + mulc(dx, BP_B0G_K, BP_B0G_S);
				if y > BP_YMAX then y := BP_YMAX; elsif y < BP_YMIN then y := BP_YMIN; end if;
				bp_x2 <= bp_x1; bp_x1 <= n155;
				bp_y2 <= bp_y1; bp_y1 <= y;
				hit_out <= y + BP_VREF;

				------------------------------------------------ fire
				-- NODE_173: inverted FIRE through R47/C28
				if I_FIRE = '1' then tgt := ZERO; else tgt := V_4; end if;
				f173 <= f173 + mulc(tgt - f173, F173_K_K, F173_K_S);

				-- NODE_178: noise and NODE_173 mixed into the 555 control voltage
				fc := mulc(f173, F_CV_G_K, F_CV_G_S);
				if noise = '1' then fc := fc + F_NOISE_CV; end if;

				-- NODE_181: 555 astable, output 1 V logic level
				fv := fvco_cap; fff := fvco_ff;
				astable('1', fc, FVCO_KC, FVCO_KD, FVCO_S, fv, fff);
				fvco_cap <= fv; fvco_ff <= fff;

				-- NODE_182: RC envelope switched by the 555
				if I_FIRE = '1' then u := HIT_U; else u := ZERO; end if;
				hc := f182_cap;
				rcdisc5(fvco_ff, u, F182_K_K, F182_K_S, hc, n182);
				f182_cap <= hc;
				fire_out <= n182;

				------------------------------------------------ mixer
				idx := 0;
				if I_VOL1 = '1'   then idx := idx + 1; end if;
				if I_VOL2 = '1'   then idx := idx + 2; end if;
				if I_MOONCR = '1' then idx := idx + 4; end if;

				-- C26: fire input coupling cap (into R43 || R91 on Galaxian)
				if I_MOONCR = '1' then
					c26 := c26_cap + mulc(fire_out - c26_cap, C26_K_MC_K, C26_K_MC_S);
				else
					c26 := c26_cap + mulc(fire_out - c26_cap, C26_K_GAL_K, C26_K_GAL_S);
				end if;
				c26_cap <= c26;
				vf := fire_out - c26;

				-- NODE_279/280 (Galaxian) or the single Moon Cresta mixer, folded into one weighted sum
				mix := resize(signed('0' & cnt_a) * to_signed(PW_A(idx), 32), 40)
				     + resize(signed('0' & cnt_c) * to_signed(PW_C(idx), 32), 40)
				     + resize(signed('0' & cnt_d) * to_signed(PW_D(idx), 32), 40)
				     + mulc(bg, MW_BG_K(idx), MW_BG_S)
				     + mulc(hit_out, MW_HIT_K(idx), MW_HIT_S)
				     + mulc(vf, MW_FIRE_K(idx), MW_FIRE_S);

				-- C46: output coupling cap
				amp := amp_cap + mulc(mix - amp_cap, AMP_K_K, AMP_K_S);
				amp_cap <= amp;
				o := mix - amp;

				-- 1.0 V = 32768, saturate
				if o >= SAT_HI then
					audio <= to_signed(32767, 16);
				elsif o < SAT_LO then
					audio <= to_signed(-32768, 16);
				else
					audio <= o(32 downto 17);
				end if;
			end if;
		end if;
	end process;

end RTL;
